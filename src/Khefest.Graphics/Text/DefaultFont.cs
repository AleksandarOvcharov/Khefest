    /// <summary>
    /// Creates a new instance of the default embedded 8x8 bitmap font.
    /// </summary>
    public static BitmapFont Create(IGpuDevice device, ResourceManager? resourceManager = null)
    {
        const int atlasWidth = 128;
        const int atlasHeight = 128;
        const int glyphWidth = 8;
        const int glyphHeight = 8;

        var pixels = new byte[atlasWidth * atlasHeight * 4];
        var glyphs = new Dictionary<char, Glyph>();

        // Generate ASCII glyphs from 32 (' ') to 126 ('~')
        for (int charCode = 32; charCode <= 126; charCode++)
        {
            char c = (char)charCode;
            int index = charCode - 32;
            int cellX = (index % 16) * glyphWidth;
            int cellY = (index / 16) * glyphHeight;

            // Render 8x8 character into pixel buffer
            DrawGlyphPixels(pixels, atlasWidth, cellX, cellY, c);
        }

        var texture = Texture2D.FromRgba(device, "DefaultFontAtlas", atlasWidth, atlasHeight, pixels, resourceManager);

        for (int charCode = 32; charCode <= 126; charCode++)
        {
            char c = (char)charCode;
            int index = charCode - 32;
            int cellX = (index % 16) * glyphWidth;
            int cellY = (index / 16) * glyphHeight;

            var region = new TextureRegion(texture, cellX, cellY, glyphWidth, glyphHeight);
            glyphs[c] = new Glyph(c, region, 0, 0, glyphWidth);
        }

        return new BitmapFont(texture, glyphHeight + 2, glyphs);
    }

    private static void DrawGlyphPixels(byte[] buffer, int pitch, int startX, int startY, char c)
    {
        var pattern = GetGlyphBitmap(c);
        for (int row = 0; row < 8; row++)
        {
            byte rowBits = pattern[row];
            for (int col = 0; col < 8; col++)
            {
                bool isSet = (rowBits & (1 << (7 - col))) != 0;
                if (isSet)
                {
                    int px = startX + col;
                    int py = startY + row;
                    int offset = (py * pitch + px) * 4;
                    buffer[offset + 0] = 255; // R
                    buffer[offset + 1] = 255; // G
                    buffer[offset + 2] = 255; // B
                    buffer[offset + 3] = 255; // A
                }
            }
        }
    }

